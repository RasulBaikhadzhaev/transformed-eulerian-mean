def test_read_era5_sample_shape_and_dims():
    req = ["THETA", "U", "V", "OMEGA", "PRESS"]
    ds = readAndTransposeData(str(ERA5_FILES[0]), req, "hybrid", "lat", "lon")
    assert set(ds.dims) == {"hybrid", "lat", "lon"}
    assert ds.sizes["hybrid"] == ERA5_SIZES["hybrid"]
    assert ds.sizes["lat"]    == ERA5_SIZES["lat"]
    assert ds.sizes["lon"]    == ERA5_SIZES["lon"]
    for v in req:
        assert v in ds


def test_read_era5_all_files_same_shape():
    req = ["THETA"]
    shapes = []
    for f in ERA5_FILES:
        ds = readAndTransposeData(str(f), req, "hybrid", "lat", "lon")
        shapes.append(tuple(ds.sizes[d] for d in ["hybrid", "lat", "lon"]))
    assert len(set(shapes)) == 1, "ERA5 sample files have inconsistent shapes"


