def test_weighted_average_single_file_is_identity():
    req = ["V"]
    ds_direct   = readAndTransposeData(str(ERA5_FILES[0]), req, "hybrid", "lat", "lon")
    ds_weighted = readDataAndGetWeightedAverage(
        [str(ERA5_FILES[0])], [1.0], req, "hybrid", "lat", "lon"
    )
    np.testing.assert_array_equal(np.array(ds_direct["V"]), np.array(ds_weighted["V"]))


def test_weighted_average_three_identical_files():
    """Average of three copies with equal weights must equal the original."""
    req = ["V"]
    ds_direct   = readAndTransposeData(str(ERA5_FILES[0]), req, "hybrid", "lat", "lon")
    ds_weighted = readDataAndGetWeightedAverage(
        [str(ERA5_FILES[0])] * 3, [1/3, 1/3, 1/3], req, "hybrid", "lat", "lon"
    )
    np.testing.assert_allclose(np.array(ds_direct["V"]), np.array(ds_weighted["V"]), rtol=1e-5)


def test_weighted_average_all_era5_files_shape():
    req = ["V", "THETA"]
    n = len(ERA5_FILES)
    ds = readDataAndGetWeightedAverage(
        [str(f) for f in ERA5_FILES], [1/n] * n, req, "hybrid", "lat", "lon"
    )
    assert ds.sizes["hybrid"] == ERA5_SIZES["hybrid"]
    assert ds.sizes["lat"]    == ERA5_SIZES["lat"]
    assert ds.sizes["lon"]    == ERA5_SIZES["lon"]


